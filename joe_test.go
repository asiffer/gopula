func testJoeSampling(t *testing.T, theta float64) {
	AC, err := NewCopula("joe", theta)
	if err != nil {
		t.Fatal(err)
	}

	M, err := AC.Sample(10000, 3)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := AC.Fit(M); err != nil {
		t.Fatal(err)
	}

	if math.Abs(AC.theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected theta* = %.3f, got %.3f", theta, AC.theta)
		out := fmt.Sprintf("%s/%s_%.2f.csv", t.ArtifactDir(), "joe_sample", theta)
		if err := saveCSV(M, out, ','); err != nil {
			t.Logf("Error saving sample to %s: %s", out, err.Error())
		} else {
			t.Logf("Saved sample to %s", out)
		}
	}
}

func TestJoeMLE(t *testing.T) {
	files, err := joeFS.ReadDir("tests/samples")
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		if file.IsDir() {
			continue
		}
		data, err := joeFS.ReadFile("tests/samples/" + file.Name())
		if err != nil {
			t.Fatal(err)
		}
		M, err := loadCSVFromBytes(data, ',')
		if err != nil {
			t.Fatal(err)
		}
		theta, err := getTheta(file.Name())
		if err != nil {
			t.Fatal(err)
		}

		t.Run(fmt.Sprintf("joe_mle_fit_%.2f", theta), func(t *testing.T) {
			testJoeMLE(t, M, theta)
		})
	}
}

func testJoeMLE(t *testing.T, M *mat.Dense, theta float64) {
	AC, err := NewCopula("joe", 2.0)
	if err != nil {
		t.Fatal(err)
	}
	result, err := AC.Fit(M)
	if err != nil {
		t.Fatal(err)
	}
	llFit := result.LogLikelihood
	if math.Abs(result.Theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected 𝜃* = %.3f, got %.3f", theta, result.Theta)
		t.Logf("MLE result: \n%+v\n", result)
	}

	ll := AC.LogLikelihood(M)
	if math.Abs(llFit-ll) > 1e-2 {
		t.Errorf("Bad likelihood computation, expected ll = %f, got %f", llFit, -ll)
	}
}

