func TestAMHDistribution(t *testing.T) {
	AC, err := NewCopula("amh", 0.5)
	if err != nil {
		t.Fatal(err)
	}

	checkTitle("Checking pdf...")
	pdf := AC.Pdf([]float64{0.5, 0.5})
	if math.Abs(pdf-1.026239) > 1e-3 {
		t.Errorf("Bad pdf computation, expected 1.08198, got %f", pdf)
		testERROR()
	} else {
		testOK()
	}

	checkTitle("Checking cdf...")
	AC.theta = 0.25
	cdf := AC.Cdf([]float64{0.25, 0.75})
	if math.Abs(cdf-0.196721) > 1e-5 {
		t.Errorf("Bad cdf computation, expected 0.22390, got %f", cdf)
		testERROR()
	} else {
		testOK()
	}

	checkTitle("Checking logpdf...")
	AC.theta = 0.3
	lpdf := AC.LogPdf([]float64{0.35, 0.85})
	if math.Abs(lpdf+0.064063) > 1e-5 {
		t.Errorf("Bad logpdf computation, expected -0.064063, got %f", lpdf)
		testERROR()
	} else {
		testOK()
	}
}

