func testAMHSampling(t *testing.T, theta float64) {
	AC, err := NewCopula("amh", theta)
	if err != nil {
		t.Fatal(err)
	}

	M, err := AC.Sample(10000, 3)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := AC.Fit(M); err != nil {
		t.Fatal(err)
	}

	if math.Abs(AC.theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected theta* = %.3f, got %.3f", theta, AC.theta)
		out := fmt.Sprintf("%s/%s_%.2f.csv", t.ArtifactDir(), "amh_sample", theta)
		if err := saveCSV(M, out, ','); err != nil {
			t.Logf("Error saving sample to %s: %s", out, err.Error())
		} else {
			t.Logf("Saved sample to %s", out)
		}
	}
}

