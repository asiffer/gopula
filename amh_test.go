func testAMHMLE(t *testing.T, M *mat.Dense, theta float64) {
	AC, err := NewCopula("amh", 0.5)
	if err != nil {
		t.Fatal(err)
	}
	result, err := AC.Fit(M)
	if err != nil {
		t.Fatal(err)
	}
	llFit := result.LogLikelihood
	if math.Abs(result.Theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected 𝜃* = %.3f, got %.3f", theta, result.Theta)
		t.Logf("MLE result: %+v\n", result)
	}

	ll := AC.LogLikelihood(M)
	if math.Abs(llFit-ll) > 1e-2 {
		t.Errorf("Bad likelihood computation, expected ll = %f, got %f", llFit, -ll)
	}
}

