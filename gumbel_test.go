func linesWithOne(M *mat.Dense) []int {
	r, c := M.Dims()
	var indices []int
	for i := 0; i < r; i++ {
		for j := 0; j < c; j++ {
			if M.At(i, j) == 1.0 {
				indices = append(indices, i)
				break

			}
		}
	}
	return indices
}

func TestGumbelSampling(t *testing.T) {
	for _, theta := range []float64{1.1, 2, 5, 10} {
		t.Run(fmt.Sprintf("gumbel_sampling_%.2f", theta), func(t *testing.T) {
			testGumbelSampling(t, theta)
		})
	}
}

func testGumbelSampling(t *testing.T, theta float64) {
	AC, err := NewCopula("gumbel", theta)
	if err != nil {
		t.Fatal(err)
	}

	M, err := AC.Sample(10000, 3)
	if err != nil {
		t.Fatal(err)
	}
	if len(linesWithOne(M)) > 0 {
		t.Logf("Warning: sample contains lines with 1.0, which can cause issues with the tests. Lines with 1.0: %v", linesWithOne(M))
	}

	if result, err := AC.Fit(M); err != nil {
		t.Fatal(err)
	} else {
		t.Logf("Results:\n%+v\n", result)
	}

	if math.Abs(AC.theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected theta* = %.3f, got %.3f", theta, AC.theta)
		out := fmt.Sprintf("%s/%s_%.2f.csv", t.ArtifactDir(), "gumbel_sample", theta)
		if err := saveCSV(M, out, ','); err != nil {
			t.Logf("Error saving sample to %s: %s", out, err.Error())
		} else {
			t.Logf("Saved sample to %s", out)
		}
	}
}

func TestGumbelMLE(t *testing.T) {
	files, err := gumbelFS.ReadDir("tests/samples")
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		if file.IsDir() {
			continue
		}
		data, err := gumbelFS.ReadFile("tests/samples/" + file.Name())
		if err != nil {
			t.Fatal(err)
		}
		M, err := loadCSVFromBytes(data, ',')
		if err != nil {
			t.Fatal(err)
		}
		theta, err := getTheta(file.Name())
		if err != nil {
			t.Fatal(err)
		}

		t.Run(fmt.Sprintf("gumbel_mle_fit_%.2f", theta), func(t *testing.T) {
			testGumbelMLE(t, M, theta)
		})
	}
}

func testGumbelMLE(t *testing.T, M *mat.Dense, theta float64) {
	AC, err := NewCopula("gumbel", 1.5)
	if err != nil {
		t.Fatal(err)
	}
	result, err := AC.Fit(M)
	if err != nil {
		t.Fatal(err)
	}
	llFit := result.LogLikelihood
	if math.Abs(result.Theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected 𝜃* = %.3f, got %.3f", theta, result.Theta)
		t.Logf("MLE result: %+v\n", result)
	}

	ll := AC.LogLikelihood(M)
	if math.Abs(llFit-ll) > 1e-2 {
		t.Errorf("Bad likelihood computation, expected ll = %f, got %f", llFit, -ll)
	}
}

