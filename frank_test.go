func TestFrankSampling(t *testing.T) {
	for _, theta := range []float64{0.1, 1, 2, 5, 10} {
		t.Run(fmt.Sprintf("frank_sampling_%.2f", theta), func(t *testing.T) {
			testFrankSampling(t, theta)
		})
	}
}

func testFrankSampling(t *testing.T, theta float64) {
	AC, err := NewCopula("frank", theta)
	if err != nil {
		t.Fatal(err)
	}

	M, err := AC.Sample(10000, 3)
	if err != nil {
		t.Fatal(err)
	}
	if _, err := AC.Fit(M); err != nil {
		t.Fatal(err)
	}

	if math.Abs(AC.theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected theta* = %.3f, got %.3f", theta, AC.theta)
		out := fmt.Sprintf("%s/%s_%.2f.csv", t.ArtifactDir(), "frank_sample", theta)
		if err := saveCSV(M, out, ','); err != nil {
			t.Logf("Error saving sample to %s: %s", out, err.Error())
		} else {
			t.Logf("Saved sample to %s", out)
		}
	}
}

func TestFrankMLE(t *testing.T) {
	files, err := frankFS.ReadDir("tests/samples")
	if err != nil {
		t.Fatal(err)
	}
	for _, file := range files {
		if file.IsDir() {
			continue
		}
		data, err := frankFS.ReadFile("tests/samples/" + file.Name())
		if err != nil {
			t.Fatal(err)
		}
		M, err := loadCSVFromBytes(data, ',')
		if err != nil {
			t.Fatal(err)
		}
		theta, err := getTheta(file.Name())
		if err != nil {
			t.Fatal(err)
		}

		t.Run(fmt.Sprintf("frank_mle_fit_%.2f", theta), func(t *testing.T) {
			testFrankMLE(t, M, theta)
		})
	}
}

func testFrankMLE(t *testing.T, M *mat.Dense, theta float64) {
	AC, err := NewCopula("frank", 0.1)
	if err != nil {
		t.Fatal(err)
	}
	result, err := AC.Fit(M)
	if err != nil {
		t.Fatal(err)
	}
	llFit := result.LogLikelihood
	if math.Abs(result.Theta-theta) > 0.15 {
		t.Errorf("Bad MLE fit, expected 𝜃* = %.3f, got %.3f", theta, result.Theta)
		t.Logf("MLE result: \n%+v\n", result)
	}

	ll := AC.LogLikelihood(M)
	if math.Abs(llFit-ll) > 1e-2 {
		t.Errorf("Bad likelihood computation, expected ll = %f, got %f", llFit, -ll)
	}
}

